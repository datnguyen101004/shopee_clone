import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

const SOURCE = 'https://danhmuchanhchinh.nso.gov.vn/DMDVHC.asmx';
const SNAPSHOT_DATE = '2025-06-30';
const SOURCE_DATE = '30/06/2025';
const EXPECTED_WARD_COUNT = 10_035;
const EXPECTED_DISTRICT_COUNT = 691;
const NO_WARD_DISTRICT_CODES = ['318', '471', '498', '536', '755'];
const outputPath = fileURLToPath(
  new URL('../apps/web/lib/legacy-vietnam-wards.generated.ts', import.meta.url),
);
const districtCatalogPath = fileURLToPath(
  new URL('../apps/web/lib/legacy-vietnam-administrative-divisions.ts', import.meta.url),
);

function decodeXml(value) {
  return value
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll('&quot;', '"')
    .replaceAll('&apos;', "'")
    .replaceAll('&amp;', '&')
    .replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code)))
    .replace(/&#x([\da-f]+);/gi, (_, code) => String.fromCodePoint(Number.parseInt(code, 16)));
}

function field(row, name) {
  const match = row.match(new RegExp(`<${name}>([\\s\\S]*?)</${name}>`));
  if (!match) throw new Error(`Missing ${name} in ward source row.`);
  return decodeXml(match[1]).trim();
}

const body = `<?xml version="1.0" encoding="utf-8"?>
<soap:Envelope xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:xsd="http://www.w3.org/2001/XMLSchema" xmlns:soap="http://schemas.xmlsoap.org/soap/envelope/">
  <soap:Body>
    <DanhMucPhuongXa xmlns="http://tempuri.org/">
      <DenNgay>${SOURCE_DATE}</DenNgay>
      <Tinh></Tinh>
      <TenTinh></TenTinh>
      <QuanHuyen></QuanHuyen>
      <TenQuanHuyen></TenQuanHuyen>
    </DanhMucPhuongXa>
  </soap:Body>
</soap:Envelope>`;

const response = await fetch(SOURCE, {
  method: 'POST',
  headers: {
    'content-type': 'text/xml; charset=utf-8',
    soapaction: '"http://tempuri.org/DanhMucPhuongXa"',
  },
  body,
});
if (!response.ok) throw new Error(`DMDVHC returned HTTP ${response.status}.`);
const xml = await response.text();
const rows = [...xml.matchAll(/<TABLE\b[^>]*>([\s\S]*?)<\/TABLE>/g)].map((match) => ({
  districtCode: field(match[1], 'MaQuanHuyen'),
  code: field(match[1], 'MaPhuongXa'),
  name: field(match[1], 'TenPhuongXa'),
}));

if (rows.length !== EXPECTED_WARD_COUNT) {
  throw new Error(`Expected ${EXPECTED_WARD_COUNT} wards, received ${rows.length}.`);
}
const wardCodes = new Set(rows.map((row) => row.code));
if (wardCodes.size !== rows.length) throw new Error('Ward codes are not globally unique.');
if (rows.some((row) => !row.districtCode || !row.code || !row.name)) {
  throw new Error('Ward source contains an empty required field.');
}

const districtCatalog = await readFile(districtCatalogPath, 'utf8');
const catalogDistrictCodes = new Set(
  [...districtCatalog.matchAll(/^      \{ code: '([0-9]{3})', name:/gm)].map((match) => match[1]),
);
const wardsByDistrict = Map.groupBy(rows, (row) => row.districtCode);
if (wardsByDistrict.size !== EXPECTED_DISTRICT_COUNT) {
  throw new Error(
    `Expected ${EXPECTED_DISTRICT_COUNT} districts with wards, received ${wardsByDistrict.size}.`,
  );
}
const unknownDistrictCodes = [...wardsByDistrict.keys()].filter(
  (code) => !catalogDistrictCodes.has(code),
);
if (unknownDistrictCodes.length > 0) {
  throw new Error(`Unknown parent district codes: ${unknownDistrictCodes.join(', ')}.`);
}
const missingDistrictCodes = [...catalogDistrictCodes]
  .filter((code) => !wardsByDistrict.has(code))
  .sort();
if (JSON.stringify(missingDistrictCodes) !== JSON.stringify(NO_WARD_DISTRICT_CODES)) {
  throw new Error(`Unexpected districts without wards: ${missingDistrictCodes.join(', ')}.`);
}

const entries = [...wardsByDistrict.entries()]
  .sort(([left], [right]) => left.localeCompare(right))
  .map(([districtCode, wards]) => {
    const serializedWards = wards
      .toSorted((left, right) => left.code.localeCompare(right.code))
      .map(
        ({ code, name }) => `    { code: ${JSON.stringify(code)}, name: ${JSON.stringify(name)} },`,
      )
      .join('\n');
    return `  ${JSON.stringify(districtCode)}: [\n${serializedWards}\n  ],`;
  })
  .join('\n');

const output = `import type { LegacyWard } from './legacy-vietnam-administrative-divisions';

/**
 * Generated by scripts/generate-legacy-vietnam-wards.mjs from ${SOURCE}
 * for the ${SNAPSHOT_DATE} legacy administrative snapshot. Do not edit manually.
 */
export const LEGACY_WARD_SNAPSHOT_COUNT = ${EXPECTED_WARD_COUNT};
export const LEGACY_WARD_DISTRICT_COUNT = ${EXPECTED_DISTRICT_COUNT};

export const LEGACY_WARDS_BY_DISTRICT: Readonly<
  Record<string, readonly LegacyWard[]>
> = {
${entries}
};
`;

await writeFile(outputPath, await format(output, { parser: 'typescript' }), 'utf8');
console.log(
  JSON.stringify({
    outputPath,
    snapshotDate: SNAPSHOT_DATE,
    wardCount: rows.length,
    districtCount: wardsByDistrict.size,
    noWardDistrictCodes: missingDistrictCodes,
  }),
);
